create or replace table `gcp-project-375309.ml.housing_detail_raw`  (
  ID INT64,
  HOUSE_ADDRESS STRING,
  ZIP STRING,
  POPULATION INT64,
  HOUSE_AGE INT64,
  TOTAL_ROOMS INT64,
  TOTAL_BEDROOMS INT64,
  HOUSE_AREA NUMERIC,
  HOUSE_PRICE INT64,
  OWNER_INCOME INT64
);

CREATE OR REPLACE TABLE `gcp-project-375309.ml.housing_detail_temp` AS
SELECT ZIP, 
ROUND( AVG(OWNER_INCOME), 2) AVG_OWNER_INCOME, 
ROUND( AVG(HOUSE_AGE), 2) AVG_HOUSE_AGE, 
ROUND( AVG(TOTAL_ROOMS), 2) AVG_TOTAL_ROOMS, 
ROUND( AVG(TOTAL_BEDROOMS), 2) AVG_TOTAL_BEDROOMS,
ROUND( AVG(HOUSE_AREA), 2) AVG_HOUSE_AREA,
FROM `gcp-project-375309.ml.housing_detail_raw`
GROUP BY ZIP;

create or replace table `gcp-project-375309.ml.housing_detail_avgd`  (
  ID INT64,
  HOUSE_ADDRESS STRING,
  AVG_OWNER_INCOME FLOAT64,
  AVG_HOUSE_AGE FLOAT64,
  AVG_TOTAL_ROOMS FLOAT64,
  AVG_TOTAL_BEDROOMS FLOAT64,
  AVG_HOUSE_AREA FLOAT64,
  POPULATION INT64,
  HOUSE_AREA FLOAT64,
  HOUSE_PRICE INT64,
  ZIP STRING
) AS
SELECT ID, HOUSE_ADDRESS, AVG_OWNER_INCOME, AVG_HOUSE_AGE, AVG_TOTAL_ROOMS, AVG_TOTAL_BEDROOMS, 
AVG_HOUSE_AREA, POPULATION, HOUSE_AREA, HOUSE_PRICE, raw.ZIP
FROM  `gcp-project-375309.ml.housing_detail_raw` raw
INNER JOIN `gcp-project-375309.ml.housing_detail_temp` tmp
ON raw.ZIP = tmp.ZIP;

