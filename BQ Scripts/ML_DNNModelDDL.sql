CREATE OR REPLACE MODEL `ml.dnn_housing` OPTIONS(
  MODEL_TYPE='DNN_REGRESSOR',
  INPUT_LABEL_COLS=['HOUSE_PRICE'],
  HIDDEN_UNITS=HPARAM_CANDIDATES([STRUCT([32,16,8]), STRUCT([8,4])]),
  DROPOUT=HPARAM_RANGE(0,0.8),
  NUM_TRIALS=10,
  BATCH_SIZE=32,
  OPTIMIZER='ADAM'
) AS SELECT * FROM `ml.housing_detail_raw`;