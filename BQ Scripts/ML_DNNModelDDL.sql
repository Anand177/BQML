CREATE OR REPLACE MODEL `ml.dnn_housing` OPTIONS(
  MODEL_TYPE = 'DNN_REGRESSOR',
  INPUT_LABEL_COLS = ['HOUSE_PRICE'],
  HIDDEN_UNITS = HPARAM_CANDIDATES([STRUCT([32,16,8]), STRUCT([8,4])]),
  ACTIVATION_FN = 'RELU',
  DROPOUT = HPARAM_RANGE(0, 0.8),
  BATCH_SIZE = 512,
  OPTIMIZER = 'ADAM',
  EARLY_STOP = TRUE,
  NUM_TRIALS = 5
) AS 
SELECT HOUSE_AGE, TOTAL_ROOMS, TOTAL_BEDROOMS, HOUSE_AREA, ZIP, POPULATION, HOUSE_PRICE 
FROM `ml.housing_detail_raw`;